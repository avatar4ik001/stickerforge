function handleAuth(e) {
  e.preventDefault();
  const email = document.getElementById('auth-email').value.trim().toLowerCase();
  const password = document.getElementById('auth-password').value;
  const name = document.getElementById('auth-name').value.trim();
  const errorEl = document.getElementById('auth-error');
  const users = JSON.parse(localStorage.getItem('sf_users') || '{}');

  if (isRegisterMode) {
    if (!name) {
      errorEl.textContent = currentLang === 'ru' ? 'Введите имя' : 'Enter your name';
      errorEl.classList.add('show');
      return;
    }
    if (users[email]) {
      errorEl.textContent = currentLang === 'ru' ? 'Email уже зарегистрирован' : 'Email already registered';
      errorEl.classList.add('show');
      return;
    }
    users[email] = { name, password, email };
    localStorage.setItem('sf_users', JSON.stringify(users));
    currentUser = { name, email };
    localStorage.setItem('sf_user', JSON.stringify(currentUser));
    showToast(currentLang === 'ru' ? 'Аккаунт создан!' : 'Account created!');
  } else {
    const user = users[email];
    if (!user || user.password !== password) {
      errorEl.textContent = currentLang === 'ru' ? 'Неверный email или пароль' : 'Invalid email or password';
      errorEl.classList.add('show');
      return;
    }
    currentUser = { name: user.name, email };
    localStorage.setItem('sf_user', JSON.stringify(currentUser));
    showToast(currentLang === 'ru' ? 'Вы вошли!' : 'Welcome back!');
  }

  renderAuthArea();
  closeAuth();
}

