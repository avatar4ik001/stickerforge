function getVolumeMultiplier(qty) {
  if (qty >= 200) return 0.55;
  if (qty >= 100) return 0.65;
  if (qty >= 50) return 0.75;
  if (qty >= 25) return 0.85;
  return 1;
}

function calcUnitPrice(sizeId, qty) {
  const size = SIZES.find(s => s.id === sizeId) || SIZES[1];
  return +(size.basePrice * getVolumeMultiplier(qty)).toFixed(2);
}

function calcTotal(sizeId, qty) {
  return +(calcUnitPrice(sizeId, qty) * qty).toFixed(2);
}

