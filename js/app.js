function handleFile(file) {
  const t = translations[currentLang];
  const maxSize = 25 * 1024 * 1024;
  if (file.size > maxSize) { showToast(t.upload_too_big); return; }
  if (!/\.(png|jpe?g|svg|pdf|ai|eps|webp)$/i.test(file.name)) {
    showToast(t.upload_bad_type); return;
  }

  customConfig.fileName = file.name;
  customConfig.fileType = file.type || file.name.split('.').pop();
  customConfig.rotation = 0;
  customConfig.scale = 1;
  customConfig.flipH = false;
  customConfig.flipV = false;

  const isImage = /image\/(png|jpe?g|webp|svg)/i.test(file.type) || /\.(png|jpe?g|webp|svg)$/i.test(file.name);
  const img = document.getElementById('editor-image');
  const empty = document.getElementById('editor-empty');
  const fname = document.getElementById('editor-filename');

  if (isImage) {
    const reader = new FileReader();
    reader.onload = (ev) => {
      customConfig.fileDataUrl = ev.target.result;
      img.src = ev.target.result;
      img.style.display = 'block';
      empty.style.display = 'none';
      fname.textContent = file.name;
      applyEditorShape();
      applyEditorTransform();
      updateCustomAddBtn();
    };
    reader.readAsDataURL(file);
  } else {
    customConfig.fileDataUrl = null;
    img.style.display = 'none';
    empty.style.display = 'none';
    fname.textContent = file.name + ' · vector/PDF ready for proof';
    applyEditorShape();
    updateCustomAddBtn();
  }
}

