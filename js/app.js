async function checkout() {
  if (!currentUser) {
    closeCart();
    openAuth('login');
    showToast(translations[currentLang].please_login);
    return;
  }
  if (!cart.length) {
    showToast(translations[currentLang].cart_empty);
    return;
  }

  const t = translations[currentLang];
  const total = cart.reduce((s, i) => s + i.total, 0);

  const payload = {
    name: currentUser.name || '',
    email: currentUser.email || '',
    total: total,
    items: cart.map(i => ({
      nameEn: i.nameEn || i.emoji || 'Item',
      nameRu: i.nameRu || i.nameEn || 'Item',
      emoji: i.emoji || '',
      qty: i.qty,
      size: i.size,
      sizeLabel: t[i.sizeLabelKey] || i.size || '',
      shape: i.shape,
      shapeLabel: t[i.shapeLabelKey] || i.shape || '',
      material: i.materialLabelKey ? (t[i.materialLabelKey] || i.material) : (i.material || ''),
      finish: i.finishLabelKey ? (t[i.finishLabelKey] || i.finish) : (i.finish || ''),
      cut: i.cutLabelKey ? (t[i.cutLabelKey] || i.cut) : (i.cut || ''),
      unitPrice: i.unitPrice,
      total: i.total,
      isCustom: !!i.isCustom,
      fileName: i.fileName || '',
      notes: i.notes || ''
    })),
    notes: cart.filter(i => i.notes).map(i => i.notes).join(' | ')
  };

  showToast(t.order_sending);

  try {
    const res = await fetch(ORDER_WEBHOOK_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok || data.ok === false) {
      throw new Error(data.error || 'request failed');
    }

    cart = [];
    saveCart();
    updateCartUI();
    closeCart();
    showToast(t.order_success);
  } catch (err) {
    console.error('Order webhook error:', err);
    showToast(t.order_failed);
  }
}

