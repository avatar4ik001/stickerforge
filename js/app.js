/* ===== 3D tilt + glare ===== */
let _tiltBound = false;
let _tiltRaf = null;
let _tiltTarget = { x: 0, y: 0 };
let _tiltCurrent = { x: 0, y: 0 };

function bindEditorTilt() {
  const stage = document.getElementById('editor-stage');
  const scene = document.getElementById('sa-scene');
  if (!stage || !scene || _tiltBound) return;
  _tiltBound = true;

  const maxTilt = 11; // degrees

  function onMove(e) {
    const rect = stage.getBoundingClientRect();
    const px = (e.clientX - rect.left) / rect.width;  // 0..1
    const py = (e.clientY - rect.top) / rect.height;
    // rotateY follows X, rotateX follows Y (inverted)
    _tiltTarget.y = (px - 0.5) * 2 * maxTilt;
    _tiltTarget.x = (0.5 - py) * 2 * maxTilt;

    // glare position on sticker
    const glare = document.getElementById('sa-glare');
    if (glare) {
      glare.style.setProperty('--glare-x', (px * 100).toFixed(1) + '%');
      glare.style.setProperty('--glare-y', (py * 100).toFixed(1) + '%');
    }
    if (!_tiltRaf) _tiltRaf = requestAnimationFrame(tickTilt);
  }

  function onLeave() {
    _tiltTarget.x = 0;
    _tiltTarget.y = 0;
    if (!_tiltRaf) _tiltRaf = requestAnimationFrame(tickTilt);
  }

  function tickTilt() {
    // smooth lerp
    _tiltCurrent.x += (_tiltTarget.x - _tiltCurrent.x) * 0.12;
    _tiltCurrent.y += (_tiltTarget.y - _tiltCurrent.y) * 0.12;
    scene.style.transform =
      'rotateX(' + _tiltCurrent.x.toFixed(2) + 'deg) rotateY(' + _tiltCurrent.y.toFixed(2) + 'deg)';

    if (Math.abs(_tiltTarget.x - _tiltCurrent.x) > 0.05 ||
        Math.abs(_tiltTarget.y - _tiltCurrent.y) > 0.05) {
      _tiltRaf = requestAnimationFrame(tickTilt);
    } else {
      _tiltRaf = null;
    }
  }

  stage.addEventListener('mousemove', onMove);
  stage.addEventListener('mouseleave', onLeave);
}

function applyEditorTransform() {
  const img = document.getElementById('editor-image');
  if (!img) return;
  const sx = (customConfig.flipH ? -1 : 1) * customConfig.scale;
  const sy = (customConfig.flipV ? -1 : 1) * customConfig.scale;
  img.style.transform = `rotate(${customConfig.rotation}deg) scale(${sx}, ${sy})`;
  const label = document.getElementById('editor-zoom-label');
  if (label) label.textContent = Math.round(customConfig.scale * 100) + '%';
}

