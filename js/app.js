function changeCartQty(idx, delta) {
  const item = cart[idx];
  if (!item) return;
  item.qty += delta;
  if (item.qty <= 0) {
    cart.splice(idx, 1);
  } else {
    item.unitPrice = calcUnitPrice(item.size, item.qty);
    item.total = +(item.unitPrice * item.qty).toFixed(2);
  }
  saveCart();
  updateCartUI();
}

